import openapiTS, { astToString } from 'openapi-typescript';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const source = new URL('../../contracts/openapi.yaml', import.meta.url);
const raw = await readFile(source, 'utf8');
// Canonical OpenAPI currently uses JSON syntax, valid YAML 1.2.
const document = JSON.parse(raw);
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);
const operations = Object.entries(document.paths).flatMap(([path, item]) =>
  Object.entries(item).filter(([method]) => methods.has(method)).map(([method, op]) => ({
    operationId: op.operationId,
    method: method.toUpperCase(),
    path,
    roles: op['x-roles'] ?? [],
    permissions: op['x-permissions'] ?? [],
    bearer: (op.security ?? document.security ?? []).some(s => 'bearerAuth' in s),
    csrf: (op.parameters ?? []).some(p => p.$ref === '#/components/parameters/Csrf'),
    idempotent: (op.parameters ?? []).some(p => p.$ref === '#/components/parameters/IdempotencyKey'),
    implementationStatus: op['x-implementation-status'] ?? 'UNVERIFIED',
  })));
if (new Set(operations.map(op => op.operationId)).size !== operations.length) {
  throw new Error('Duplicate operationId in canonical contract');
}
const metadata = `// Generated by scripts/generate-api.mjs; do not edit. Contract coverage is not backend implementation.\nexport const contractSha256 = ${JSON.stringify(createHash('sha256').update(raw).digest('hex'))};\nexport const contractVersion = ${JSON.stringify(document.info.version)};\nexport const operations = ${JSON.stringify(operations, null, 2)} as const;\nexport type OperationId = (typeof operations)[number]['operationId'];\nexport type Permission = (typeof operations)[number]['permissions'][number];\n`;
const generated = astToString(await openapiTS(document));
const outputs = [['schema.d.ts', generated], ['operations.ts', metadata]];
await mkdir(new URL('../src/api/', import.meta.url), { recursive: true });
for (const [name, expected] of outputs) {
  const target = new URL(`../src/api/${name}`, import.meta.url);
  if (process.argv.includes('--check')) {
    let actual;
    try { actual = await readFile(target, 'utf8'); } catch { throw new Error(`${name} missing; run npm run generate:api`); }
    if (actual !== expected) throw new Error(`${name} is stale; run npm run generate:api`);
  } else await writeFile(target, expected);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${operations.length} OpenAPI operations; implementation status remains unverified by this script.`);
